#!/usr/bin/env python3
"""Generate each ZSvirt watchface's build inputs from its device matrix."""
import argparse
from hashlib import sha256
from itertools import product
import json
import os
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
APPS = {
    "time": {"root": ROOT, "stem": "zsvirt-time", "entry": "ZsvirtTimeApp"},
    "girl": {"root": ROOT / "faces/zsvirt-girl", "stem": "zsvirt-girl", "entry": "ZsvirtGirlApp"},
}
NS = "http://www.garmin.com/xml/connectiq"
ET.register_namespace("iq", NS)


def girl_resource_profile(target):
    colors = target["resource_palette_colors"]
    if colors is not None:
        entries = tuple(color.upper() for color in colors)
        opaque = tuple(color for color in entries if color != "TRANSPARENT")
        if not opaque or any(len(color) != 6 for color in opaque):
            raise ValueError(f"Invalid resource palette: {target['ciq_product_id']}")
        rgb = tuple(tuple(bytes.fromhex(color)) for color in opaque)
        digest = sha256(",".join(entries).encode("ascii")).hexdigest()[:16]
        return f"palette-{len(entries)}-{digest}", rgb
    if target["display_type"] == "mip" and target["pixel_format"] == "ARGB2222":
        return "argb2222", tuple(product((0, 85, 170, 255), repeat=3))
    if target["display_type"] == "amoled" and target["bits_per_pixel"] == 16:
        return "rgb565", None
    raise ValueError(f"Unsupported Girl pixel format: {target['ciq_product_id']}")


def girl_resource_paths(target):
    profile, _ = girl_resource_profile(target)
    screen = target["resolution"]
    icon = target["launcher_icon"]
    return (
        Path("resources-portraits") / f"{screen['width']}x{screen['height']}" / profile,
        Path("resources-launchers") / f"{icon['width']}x{icon['height']}" / profile,
    )


def write_configuration(targets, destination, face):
    ids = [target["ciq_product_id"] for target in targets]
    if not ids or len(ids) != len(set(ids)) or not all(target["watchface_supported"] for target in targets):
        raise ValueError("Device matrix must contain unique supported Watch Face targets")
    destination.mkdir(parents=True, exist_ok=True)
    prefix = Path(os.path.relpath(ROOT, destination))
    application = APPS[face]
    app_prefix = Path(os.path.relpath(application["root"], destination))
    matrix = json.loads((application["root"] / "docs/compatibility.json").read_text())
    manifest = ET.Element(f"{{{NS}}}manifest", {"version": "3"})
    app = ET.SubElement(manifest, f"{{{NS}}}application", {
        "id": matrix["application_id"], "type": "watchface", "name": "@Strings.AppName",
        "entry": application["entry"], "launcherIcon": "@Drawables.LauncherIcon",
        "minApiLevel": matrix["minimum_api"]})
    products = ET.SubElement(app, f"{{{NS}}}products")
    for device in ids:
        ET.SubElement(products, f"{{{NS}}}product", {"id": device})
    ET.SubElement(app, f"{{{NS}}}permissions")
    languages = ET.SubElement(app, f"{{{NS}}}languages")
    for language in ("eng", "zhs"):
        ET.SubElement(languages, f"{{{NS}}}language").text = language
    ET.SubElement(app, f"{{{NS}}}barrels")
    ET.indent(manifest)
    (destination / "manifest.xml").write_text(ET.tostring(manifest, encoding="unicode") + "\n")
    sources = f"{app_prefix / 'source'};{prefix / 'shared'};{prefix / 'tests'}"
    base_sources = sources + f";{prefix / 'profiles/mip'}"
    jungle = ["# Generated by scripts/configure.py from the application's docs/compatibility.json",
              "project.manifest = manifest.xml",
              f"base.sourcePath = {base_sources}",
              f"base.resourcePath = {app_prefix / 'resources'}", ""]
    if face == "girl":
        jungle.extend([f"base.lang.zhs = {app_prefix / 'resources-zhs'}", ""])
    for target in targets:
        device = target["ciq_product_id"]
        technology = target["display_type"]
        if technology not in ("mip", "amoled"):
            raise ValueError(f"Unsupported display technology: {device}: {technology}")
        width = target["resolution"]["width"]
        icon = target["launcher_icon"]
        icon_size = f"{icon['width']}x{icon['height']}"
        device_sources = sources + f";{prefix / ('profiles/' + technology)}"
        device_resources = str(app_prefix / "resources")
        if face == "time":
            device_resources += f";{prefix / ('resources-logos/' + str(width))};{prefix / ('resources-launchers/' + icon_size)}"
        else:
            device_resources += "".join(f";{app_prefix / path}" for path in girl_resource_paths(target))
        jungle.extend([
            f"{device}.sourcePath = {device_sources}",
            f"{device}.resourcePath = {device_resources}", ""])
    (destination / "monkey.jungle").write_text("\n".join(jungle))
    return ids


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--face", choices=APPS, default="time")
    args = parser.parse_args()
    app_root = APPS[args.face]["root"]
    targets = json.loads((app_root / "docs/compatibility.json").read_text())["targets"]
    ids = write_configuration(targets, app_root, args.face)
    print(f"Configured {len(ids)} official targets: {', '.join(ids)}")


if __name__ == "__main__":
    main()
